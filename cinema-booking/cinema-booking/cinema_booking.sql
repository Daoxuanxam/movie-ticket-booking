DROP TABLE IF EXISTS `booking_seats`;
DROP TABLE IF EXISTS `bookings`;
DROP TABLE IF EXISTS `showtimes`;
DROP TABLE IF EXISTS `seats`;
DROP TABLE IF EXISTS `halls`;
DROP TABLE IF EXISTS `cinemas`;
DROP TABLE IF EXISTS `movies`;
DROP TABLE IF EXISTS `discount_codes`;
DROP TABLE IF EXISTS `menu`;
DROP TABLE IF EXISTS `users`;

-- Bật lại kiểm tra khoá ngoại
SET FOREIGN_KEY_CHECKS = 1;

-- =====================================================================
-- 3. TẠO CẤU TRÚC CÁC BẢNG (TABLE STRUCTURES)
-- =====================================================================

-- -----------------------------------------------------
-- Bảng: users (Người dùng: Admin, Khách hàng)
-- -----------------------------------------------------
CREATE TABLE `users` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `full_name` VARCHAR(255) NOT NULL COMMENT 'Họ và tên',
    `email` VARCHAR(255) NOT NULL UNIQUE COMMENT 'Email đăng nhập',
    `phone` VARCHAR(50) DEFAULT NULL COMMENT 'Số điện thoại',
    `password_hash` VARCHAR(255) NOT NULL COMMENT 'Mật khẩu',
    `role` VARCHAR(20) NOT NULL DEFAULT 'customer' COMMENT 'customer | admin',
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1=hoạt động, 0=khóa',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Ngày tạo',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Ngày cập nhật',
    INDEX `idx_users_role` (`role`),
    INDEX `idx_users_active` (`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng người dùng';

-- -----------------------------------------------------
-- Bảng: menu (Menu điều hướng động trên Navbar)
-- -----------------------------------------------------
CREATE TABLE `menu` (
    `menu_id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `parent_id` BIGINT DEFAULT NULL COMMENT 'ID menu cha',
    `menu_name` VARCHAR(100) NOT NULL COMMENT 'Tên hiển thị menu',
    `menu_url` VARCHAR(255) DEFAULT NULL COMMENT 'Đường dẫn liên kết',
    `sort_order` INT DEFAULT 0 COMMENT 'Thứ tự hiển thị',
    `is_active` TINYINT(1) DEFAULT 1 COMMENT '1=hiển thị, 0=ẩn',
    CONSTRAINT `fk_menu_parent` FOREIGN KEY (`parent_id`) REFERENCES `menu` (`menu_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng menu điều hướng động';

-- -----------------------------------------------------
-- Bảng: cinemas (Cụm rạp chiếu phim)
-- -----------------------------------------------------
CREATE TABLE `cinemas` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `name` VARCHAR(255) NOT NULL COMMENT 'Tên cụm rạp',
    `address` VARCHAR(255) NOT NULL COMMENT 'Địa chỉ cụm rạp',
    `city` VARCHAR(100) NOT NULL COMMENT 'Tỉnh/Thành phố',
    `phone` VARCHAR(50) DEFAULT NULL COMMENT 'Số điện thoại liên hệ',
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1=hoạt động, 0=tạm đóng',
    INDEX `idx_cinemas_city` (`city`),
    INDEX `idx_cinemas_active` (`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng cụm rạp chiếu phim';

-- -----------------------------------------------------
-- Bảng: halls (Phòng chiếu theo rạp)
-- -----------------------------------------------------
CREATE TABLE `halls` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `cinema_id` INT NOT NULL COMMENT 'Mã rạp',
    `name` VARCHAR(100) NOT NULL COMMENT 'Tên phòng chiếu',
    `hall_type` VARCHAR(20) NOT NULL DEFAULT 'TWO_D' COMMENT 'TWO_D, THREE_D, IMAX, FOUR_DX',
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1=hoạt động, 0=bảo trì',
    CONSTRAINT `fk_halls_cinema` FOREIGN KEY (`cinema_id`) REFERENCES `cinemas` (`id`) ON DELETE CASCADE,
    INDEX `idx_halls_cinema_id` (`cinema_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng phòng chiếu phim';

-- -----------------------------------------------------
-- Bảng: seats (Sơ đồ ghế theo từng phòng chiếu)
-- -----------------------------------------------------
CREATE TABLE `seats` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `hall_id` INT NOT NULL COMMENT 'Mã phòng chiếu',
    `row_label` VARCHAR(10) NOT NULL COMMENT 'Hàng ghế: A, B, C...',
    `seat_number` INT NOT NULL COMMENT 'Số ghế trong hàng: 1, 2, 3...',
    `seat_type` VARCHAR(50) NOT NULL DEFAULT 'standard' COMMENT 'standard, vip, couple',
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1=khả dụng, 0=hỏng',
    CONSTRAINT `fk_seats_hall` FOREIGN KEY (`hall_id`) REFERENCES `halls` (`id`) ON DELETE CASCADE,
    CONSTRAINT `uq_seats_hall_row_num` UNIQUE (`hall_id`, `row_label`, `seat_number`),
    INDEX `idx_seats_hall_id` (`hall_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng ghế ngồi';

-- -----------------------------------------------------
-- Bảng: movies (Danh sách phim)
-- -----------------------------------------------------
CREATE TABLE `movies` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `title` VARCHAR(255) NOT NULL COMMENT 'Tên phim',
    `description` TEXT DEFAULT NULL COMMENT 'Mô tả nội dung',
    `actors` TEXT DEFAULT NULL COMMENT 'Diễn viên, đạo diễn',
    `duration` INT NOT NULL COMMENT 'Thời lượng (phút)',
    `rated` VARCHAR(20) DEFAULT NULL COMMENT 'Phân loại độ tuổi: P, T13, T16, T18',
    `release_date` DATE DEFAULT NULL COMMENT 'Ngày khởi chiếu',
    `end_date` DATE DEFAULT NULL COMMENT 'Ngày kết thúc chiếu',
    `poster_url` VARCHAR(500) DEFAULT NULL COMMENT 'URL poster ảnh',
    `trailer_url` VARCHAR(500) DEFAULT NULL COMMENT 'URL trailer youtube',
    `status` VARCHAR(20) NOT NULL DEFAULT 'coming_soon' COMMENT 'now_showing, coming_soon, ended',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Ngày tạo',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Ngày cập nhật',
    INDEX `idx_movies_status` (`status`),
    INDEX `idx_movies_release_date` (`release_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng phim';

-- -----------------------------------------------------
-- Bảng: showtimes (Suất chiếu phim)
-- -----------------------------------------------------
CREATE TABLE `showtimes` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `movie_id` INT NOT NULL COMMENT 'Phim chiếu',
    `hall_id` INT NOT NULL COMMENT 'Phòng chiếu',
    `start_time` DATETIME NOT NULL COMMENT 'Giờ bắt đầu',
    `end_time` DATETIME NOT NULL COMMENT 'Giờ kết thúc',
    `language` VARCHAR(20) NOT NULL DEFAULT 'subtitled' COMMENT 'original, dubbed, subtitled',
    `status` VARCHAR(20) NOT NULL DEFAULT 'active' COMMENT 'active, cancelled, finished',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Ngày tạo',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Ngày cập nhật',
    CONSTRAINT `fk_showtimes_movie` FOREIGN KEY (`movie_id`) REFERENCES `movies` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_showtimes_hall` FOREIGN KEY (`hall_id`) REFERENCES `halls` (`id`) ON DELETE CASCADE,
    INDEX `idx_showtimes_movie_id` (`movie_id`),
    INDEX `idx_showtimes_hall_id` (`hall_id`),
    INDEX `idx_showtimes_start_time` (`start_time`),
    INDEX `idx_showtimes_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng suất chiếu';

-- -----------------------------------------------------
-- Bảng: discount_codes (Mã giảm giá)
-- -----------------------------------------------------
CREATE TABLE `discount_codes` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `code` VARCHAR(50) NOT NULL UNIQUE COMMENT 'Mã giảm giá',
    `description` VARCHAR(255) DEFAULT NULL COMMENT 'Mô tả',
    `discount_type` VARCHAR(20) NOT NULL COMMENT 'percent | fixed',
    `discount_value` DECIMAL(12, 2) NOT NULL COMMENT 'Giá trị giảm',
    `min_order` DECIMAL(12, 2) NOT NULL DEFAULT 0.00 COMMENT 'Đơn tối thiểu',
    `max_uses` INT DEFAULT NULL COMMENT 'Lượt dùng tối đa',
    `used_count` INT NOT NULL DEFAULT 0 COMMENT 'Số lượt đã dùng',
    `valid_from` DATETIME NOT NULL COMMENT 'Bắt đầu',
    `valid_until` DATETIME NOT NULL COMMENT 'Hết hạn',
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1=khả dụng, 0=khóa',
    INDEX `idx_discount_codes_code` (`code`),
    INDEX `idx_discount_codes_active` (`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng mã khuyến mãi';

-- -----------------------------------------------------
-- Bảng: bookings (Đơn đặt vé)
-- -----------------------------------------------------
CREATE TABLE `bookings` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `user_id` INT NOT NULL COMMENT 'Khách hàng',
    `showtime_id` INT NOT NULL COMMENT 'Suất chiếu',
    `booking_code` VARCHAR(50) NOT NULL UNIQUE COMMENT 'Mã đặt vé',
    `subtotal` DECIMAL(12, 2) NOT NULL COMMENT 'Tạm tính',
    `discount_amount` DECIMAL(12, 2) NOT NULL DEFAULT 0.00 COMMENT 'Giảm giá',
    `total_amount` DECIMAL(12, 2) NOT NULL COMMENT 'Tổng tiền thanh toán',
    `payment_method` VARCHAR(50) DEFAULT NULL COMMENT 'momo, vnpay, banking, cash',
    `status` VARCHAR(20) NOT NULL DEFAULT 'pending' COMMENT 'pending, confirmed, cancelled, refunded',
    `payment_status` VARCHAR(20) NOT NULL DEFAULT 'unpaid' COMMENT 'unpaid, paid, refunded',
    `paid_at` DATETIME DEFAULT NULL COMMENT 'Thời điểm thanh toán',
    `cancelled_at` DATETIME DEFAULT NULL COMMENT 'Thời điểm hủy',
    `cancel_reason` VARCHAR(255) DEFAULT NULL COMMENT 'Lý do hủy',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Ngày tạo đơn',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Ngày cập nhật',
    CONSTRAINT `fk_bookings_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
    CONSTRAINT `fk_bookings_showtime` FOREIGN KEY (`showtime_id`) REFERENCES `showtimes` (`id`) ON DELETE RESTRICT,
    INDEX `idx_bookings_user_id` (`user_id`),
    INDEX `idx_bookings_showtime_id` (`showtime_id`),
    INDEX `idx_bookings_created_at` (`created_at`),
    INDEX `idx_bookings_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng đơn đặt vé';

-- -----------------------------------------------------
-- Bảng: booking_seats (Chi tiết ghế của đơn đặt)
-- -----------------------------------------------------
CREATE TABLE `booking_seats` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `booking_id` INT NOT NULL COMMENT 'Mã đơn vé',
    `seat_id` INT NOT NULL COMMENT 'Mã ghế',
    `seat_type` VARCHAR(50) NOT NULL COMMENT 'standard, vip, couple',
    `price` DECIMAL(12, 2) NOT NULL COMMENT 'Giá vé',
    CONSTRAINT `fk_bs_booking` FOREIGN KEY (`booking_id`) REFERENCES `bookings` (`id`) ON DELETE CASCADE,
    CONSTRAINT `fk_bs_seat` FOREIGN KEY (`seat_id`) REFERENCES `seats` (`id`) ON DELETE RESTRICT,
    INDEX `idx_bs_booking_id` (`booking_id`),
    INDEX `idx_bs_seat_id` (`seat_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng chi tiết ghế đặt';

-- -----------------------------------------------------
-- Bảng: payments (Giao dịch thanh toán)
-- -----------------------------------------------------
CREATE TABLE `payments` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `booking_id` INT NOT NULL COMMENT 'Mã đơn vé',
    `payment_code` VARCHAR(50) NOT NULL UNIQUE COMMENT 'Mã giao dịch nội bộ / vnp_TxnRef',
    `payment_method` VARCHAR(50) NOT NULL COMMENT 'momo, vnpay, banking, card, cash',
    `amount` DECIMAL(12, 2) NOT NULL COMMENT 'Số tiền thanh toán',
    `status` VARCHAR(20) NOT NULL DEFAULT 'pending' COMMENT 'pending, success, failed, refunded',
    `gateway_transaction_id` VARCHAR(100) DEFAULT NULL COMMENT 'Mã giao dịch Cổng thanh toán (VNPay/MoMo)',
    `bank_code` VARCHAR(50) DEFAULT NULL COMMENT 'Ngân hàng thực hiện giao dịch (NCB, VCB, APP, ...)',
    `response_code` VARCHAR(50) DEFAULT NULL COMMENT 'Mã phản hồi từ cổng',
    `pay_date` DATETIME DEFAULT NULL COMMENT 'Thời gian thanh toán thành công',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Thời điểm tạo giao dịch',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Thời điểm cập nhật',
    CONSTRAINT `fk_payments_booking` FOREIGN KEY (`booking_id`) REFERENCES `bookings` (`id`) ON DELETE CASCADE,
    INDEX `idx_payments_booking_id` (`booking_id`),
    INDEX `idx_payments_code` (`payment_code`),
    INDEX `idx_payments_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Bảng giao dịch thanh toán';

